from evidence import ROOT, source_digest, utc


def command_output(command):
    return subprocess.check_output(command, text=True, cwd=ROOT).strip()


def render(directory, report):
    faults = json.loads((directory / 'scenarios/results.json').read_text())
    demo = json.loads((directory / 'demo/results.json').read_text())
    manual = json.loads((directory / 'manual/results.json').read_text())
    assert (faults['passed'], faults['failed']) == (10, 0)
    assert (demo['passed'], demo['failed']) == (1, 0)
    assert (manual['passed'], manual['failed']) == (1, 0)
    cases = {case['name']: case['measurements'] for case in faults['scenarios']}
    builds = ('build', 'build-sanitize', 'build-tsan', 'build-ci', 'build-ci-sanitize', 'build-release')
    counts = {}
    for build in builds:
        log = (ROOT / build / 'Testing/Temporary/LastTest.log').read_text()
        counts[build] = [int(n) for n in re.findall(r'\[\s+PASSED\s+\]\s+(\d+) test', log)]
        assert counts[build] == [13, 26, 6], (build, counts[build])
        shutil.copyfile(ROOT / build / 'Testing/Temporary/LastTest.log', directory / f'{build}-ctest.log')
    local = (directory / 'local.log').read_text()
    ci = (directory / 'ci.log').read_text()
    assert 'ERROR SUMMARY: 0 errors' in local
    assert len(re.findall('PASS Checkpoint 1 integration:', local)) == 2
    assert len(re.findall('PASS Checkpoint 2 integration:', local)) == 2
    assert len(re.findall('PASS Checkpoint 3 integration:', local)) == 3
    assert 'database contract 5/5' in ci
    assert 'Ran 7 tests' in local and 'Ran 7 tests' in ci
    hardening = {}
    for variant in ('release', 'sanitize', 'tsan'):
        result = json.loads((directory / f'hardening-{variant}/results.json').read_text())
        assert (result['passed'], result['failed']) == (5, 0)
        hardening[variant] = {case['name']: case['measurements'] for case in result['scenarios']}
    release = (directory / 'release.log').read_text()
    assert all(name in release for name in ('PASS Checkpoint 1 integration:',
                                           'PASS Checkpoint 2 integration:', 'PASS Checkpoint 3 integration:'))
    fuzz = (directory / 'fuzz/fuzzer.log').read_text()
    total = re.search(r'Done (\d+) runs in (\d+) second', fuzz)
    assert total, 'missing successful libFuzzer completion'
    fuzz_runs, fuzz_seconds = map(int, total.groups())
    peak = int(re.search(r'stat::peak_rss_mb:\s+(\d+)', fuzz)[1])
    story = demo['scenarios'][0]['measurements']
    history = json.loads((directory / 'demo/interview/history.json').read_text())
    checkpoints = json.loads((directory / 'demo/interview/checkpoints.json').read_text())
    assert sum(row['kind'] == 'reading' for row in history) == story['total_written'] == 12
    assert sum(row['reading_drops'] for row in checkpoints) == story['dropped'] == 7
    assert all(row['observed_at'] and row['monotonic_ms'] > 0 for row in history)
    report['observed_counts'] = dict(c_cases=counts, python_cases_per_invocation=7,
                                   fault_cases=10, database_contract_cases=5,
                                   hardening_cases_per_variant=5, hardening_variants=3,
                                   demo_cases=1, manual_exchange_cases=1,
                                   fuzz_executions=fuzz_runs, fuzz_seconds=fuzz_seconds,
                                   demo_history_rows=len(history), demo_checkpoints=len(checkpoints))
    path = directory.relative_to(ROOT)
    lines = [
        '# Vigil core verification', '',
        'Generated by `tests/verify_checkpoint.py` from successful observed commands,',
        'scenario JSON, CTest logs, libFuzzer output and SQL exports. Numbers below',
        'describe this run, not universal latency or throughput guarantees.', '',
        f"- UTC run: `{report['started_utc']}` to `{report['ended_utc']}`.",
        f"- Checked-out commit before final evidence commit: `{report['commit']}`.",
        '- The checkpoint commit containing this report includes the tested working-tree changes.',
        f"- Implementation SHA-256: `{report['source_sha256']}` (algorithm: `tests/evidence.py`).",
        f'- Full local transcripts/JSON/configs/SQL: `{path}/` (ignored; retained on this machine).',
        '- Hosted GitHub Actions has **not** been run or claimed green. Its exact command suite passed locally.',
        '', '## Environment', '', '```text', report['environment'], '```', '',
        '## Commands and observed results', '',
        '| Command (inside Linux) | Exit | Elapsed seconds, this run |',
        '| --- | --- | --- |']
    for item in report['commands']:
        lines.append(f"| `{shlex.join(item['command'])}` | {item['exit_code']} | {item['elapsed_s']:.3f} |")
    lines += ['', '- Six C builds each passed **13 protocol + 26 monitor + 6 queue = 45** cases (270 executions, zero failures).',
              '- Seven Python cases passed in each of two invocations; five non-vcan PostgreSQL contracts passed.',
              '- Decoder and monitor real-vcan suites each passed in Debug, ASan/UBSan and Release; persistence also passed under TSan.',
              '- Five final hardening scenarios passed in Release, ASan/UBSan and TSan (15 executions).',
              '- Ten fault cases, one interview story and one independent can-utils exchange passed; zero failures.',
              '- GCC and Clang strict builds, GCC `-fanalyzer`, ASan/UBSan and TSan completed without findings.',
              '- Helgrind reported zero errors on the six queue cases; library suppressions remain enabled by Valgrind.',
              '', '## Final hardening', '',
              'Each variant uses real vcan/PostgreSQL; full JSON and raw logs are retained.', '',
              '| Variant | Rapid restart | Repeated outages | Permission recovery | Maximum alarm snapshot | Invalid startups |',
              '| --- | --- | --- | --- | --- | --- |']
    for variant, results in hardening.items():
        rapid = results['rapid-restarts']
        outage = results['repeated-outages']
        lines.append(f"| {variant} | Six cycles, 18 rejected, 12 resets, 18 recoveries; alarm ages {rapid['detection_ages_ms']} ms | "
                     f"Three cycles, 14 arrivals, nine retained, five lost; outages {outage['outage_durations_ms']} ms | "
                     '42501 then five retained, zero drops | 16 pods, 193 entries; 64 readings/32 heartbeats | Ten exit 2 |')
    lines += ['', '## Scenario measurements', '', '| Scenario | Observed result |', '| --- | --- |']
    silent = cases['silent-pod']
    ages = [s['detection_age_ms'] for s in silent['sources']]
    lines += [f"| Silent pod and return | Deadline 500 ms; alarm ages {ages} ms (heartbeat, temperature, door); current=0 while stale; three recoveries |",
              '| Malformed | One length and one CRC rejection; unchanged reading, timestamp and high-alarm lifecycle |',
              '| Non-advancing | One repeat and two old/ambiguous rejected; accepted baseline remains 10 |',
              '| Counter jump | 10 → 14: exactly three inferred lost; both readings accepted; new value=2400 |',
              '| Hysteresis | Eight readings; one raise at 2700 and one clear at 2600 |']
    for name in ('database-backfill', 'queue-overflow'):
        m = cases[name]
        lines.append(f"| {name} | Capacity {m['capacity']}; arrivals {m['outage_readings']}; retained {m['retained']}; "
                     f"drops {m['dropped']}; gaps {m['gap_markers']}; live alarm age {m['alarm_age_ms']} ms; outage {m['outage_ms']} ms |")
    m = cases['crash-systemd']
    lines.append(f"| Crash under systemd | Two committed rows retained; exactly three pending readings lost; "
                 f"SIGKILL restart observed after {m['restarted_ms']-m['killed_ms']} ms; {m['restarts']} restarts including watchdog; UID {m['uid']} |")
    for name in ('high-rate', 'receive-overflow'):
        m = cases[name]
        lines.append(f"| {name} | Sent {m['sent']} = received {m['received']} + kernel drops {m['kernel_drops']}; "
                     f"accepted readings {m['accepted_readings']}; rejected {m['rejected']}; "
                     f"offered burst rate {m['offered_frames_per_s']} frames/s over {m['send_duration_s']:.6f} s |")
    lines += ['', 'Detection bounds are deadline + 20 ms tick + up to 200 ms explicit test scheduling allowance.',
              'The implementation is not hard real-time. Receive-overflow deliberately pauses the receiver;',
              'its rate is not a throughput benchmark. Both load cases disable persistence and separately',
              'count a final heartbeat probe. Kernel drops are exact socket delivery counts; 8-bit sequence',
              'loss is ambiguous across large gaps/wraps and must not be added to kernel drops.', '',
              'Other regression measurements, copied from the actual final local log:', '', '```text']
    lines += [line for line in local.splitlines() if line.startswith(('PASS backfill:', 'PASS overflow:',
              'PASS event overflow:', 'PASS unresponsive TCP:', 'PASS systemd:', 'PASS locked PostgreSQL:',
              'PASS server statement_timeout:', 'PASS lost COMMIT response:'))]
    lines += ['```', '', '## Fuzzer and sanitizers', '',
              f'libFuzzer executed **{fuzz_runs:,}** inputs in **{fuzz_seconds} seconds**, peak RSS {peak} MiB.',
              'The run exited 0, with no crash, ASan/UBSan diagnostic or decoder invariant failure.',
              'The seed-1 corpus includes literal wire fixtures, malformed lengths/flags/IDs/CRC/enums.',
              'Both the target and decoder are instrumented. The target checks rejection immutability,',
              'successful field invariants and null-argument handling; it does not fuzz the monitor, queue,',
              'libpq, systemd or a physical bus. Fixed seed improves repeatability; time-limited execution',
              'counts depend on machine load. This finite run is evidence, not proof of no defects.', '',
              'Actual command:', '', '```sh', (directory / 'fuzz/command.txt').read_text().strip(), '```', '',
              '## Interview story and database inspection', '',
              f"Run UUID `{story['run_id']}`. Last valid temperature at `{story['last_valid_ms']}` monotonic ms; "
              f"communication alarm at `{story['alarm_ms']}`: **{story['detection_age_ms']} ms**.",
              f"Eight pre-outage readings committed. During **{story['outage_ms']} ms** observed database outage, "
              'eleven new readings arrived; capacity four retained the newest four and counted seven drops.',
              f"After recovery: **12 total SQL readings**, **{story['gap_markers']} gap marker(s)**, seven reading drops, "
              'zero event drops and zero abandoned records. Current high/stale alarms remained visible during the outage.',
              f"Export inspected: {len(history)} history rows, {len(checkpoints)} checkpoints, all history rows with UTC and monotonic timestamps.",
              f"Preserved values: `{story['sql_values']}`.", '', '## Manual command evidence', '',
              'The [manual checklist](MANUAL_CAN.md) remains available for a human operator.',
              'The following literal can-utils exchange was executed by the recording script; it is not a human sign-off.',
              'Decoder results were ok/length/crc; deliberate rejection exit status was 1. Candump observed:', '', '```text',
              manual['scenarios'][0]['measurements']['candump'].rstrip(), '```', '',
              '## Findings and limits', '',
              '- Checkpoint 5 fixed SQLSTATE identifier coercion in the evidence parser; 08001/08006 now retain their leading zero. '
              'No wire behavior changed. See FINAL_VERIFICATION.md for the complete final audit record.',
              '- VM stalls can batch differing readings at the same receive timestamp and trigger the rate rule. '
              'Transport/count and silence fixtures disable that unrelated rule; deterministic C tests retain exact rate boundaries. '
              'The production receive-time plausibility policy is unchanged and this batching limitation is documented.',
              '- A timestamped result is only accepted if its assertions and command exit status succeed; failed development runs remain in local artifacts.',
              '- vcan exercises real Linux application behavior, not physical CAN arbitration, bitrate ceilings, electrical faults, wiring or bus-off.',
              '- The queue is volatile: pending N readings + 256 events + at most 32 immutable in-flight records. '
              'Only pending unsubmitted records are evicted; a lost COMMIT response can leave unconfirmed rows already in SQL.',
              '- The known stopped-database crash fixture can measure three lost readings. A restarted daemon cannot reconstruct unknown prior-run losses '
              'or emit an honest exact gap for memory that vanished. No disk spool or crash durability is claimed.',
              '- CRC/counters do not authenticate senders. Flatness is suspicion, not proof of a failed sensor. '
              'Diagnostic regular-file I/O can still block; backpressure can drop counted output lines.',
              '- No hardware, production scale, hard real-time, A-Link/NetBotz compatibility or Buildroot claim. '
              'The core and evidence satisfy the version 3 brief subject to the documented architectural/process refinements in DECISIONS.md.', '']
    (ROOT / 'docs/VERIFICATION.md').write_text('\n'.join(lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--clean', action='store_true', required=True)
    parser.add_argument('--output', default='artifacts/checkpoint-5-' + time.strftime('%Y%m%dT%H%M%SZ', time.gmtime()))
    args = parser.parse_args()
    if sys.platform != 'linux' or sys.flags.optimize:
        raise RuntimeError('real Linux required; assertions must remain enabled')
    directory = (ROOT / args.output).resolve()
    directory.relative_to(ROOT / 'artifacts')
    directory.mkdir(parents=True, exist_ok=False)
    (directory / 'diagnostics').mkdir()
    report = dict(started_utc=utc(), commit=command_output(['git', 'rev-parse', 'HEAD']),
                  source_sha256=source_digest(), commands=[])
    report['environment'] = '\n'.join(command_output(cmd) for cmd in (
        ['uname', '-a'], ['cat', '/etc/os-release'], ['gcc', '--version'], ['clang', '--version'],
        ['psql', '--version'], ['systemctl', '--version'], ['cmake', '--version'], ['valgrind', '--version']))
    def save():
        (directory / 'gate.json').write_text(json.dumps(report, indent=2) + '\n')
    save()
    # A quiet bus is a prerequisite, not a substitute for any Linux gate.
    subprocess.run(['./scripts/vcan-up'], check=True)
    with socket.socket(socket.AF_CAN, socket.SOCK_RAW, socket.CAN_RAW) as bus:
        bus.bind(('vcan0',))
        bus.settimeout(0.2)
        try:
            traffic = bus.recv(16)
        except TimeoutError:
            traffic = None
        assert traffic is None, 'vcan0 is busy; stop other simulators before the gate'
    commands = [
        ('local', ['./scripts/check', '--clean']),
        ('ci', ['./scripts/check-ci', '--clean']),
        ('release', ['./scripts/check-release', '--clean']),
        ('hardening-release', [sys.executable, 'tests/final_hardening.py', '--daemon', 'build-release/vigild',
                               '--output', str(directory / 'hardening-release')]),
        ('hardening-sanitize', [sys.executable, 'tests/final_hardening.py', '--daemon', 'build-sanitize/vigild',
                                '--output', str(directory / 'hardening-sanitize')]),
        ('hardening-tsan', ['setarch', os.uname().machine, '-R', sys.executable, 'tests/final_hardening.py',
                            '--daemon', 'build-tsan/vigild', '--output', str(directory / 'hardening-tsan')]),
        ('scenarios', [sys.executable, 'tests/fault_scenarios.py', '--output', str(directory / 'scenarios')]),
        ('demo', [sys.executable, 'tests/interview_demo.py', '--output', str(directory / 'demo')]),
        ('manual', [sys.executable, 'tests/manual_commands.py', '--output', str(directory / 'manual')]),
        ('fuzz', ['./scripts/fuzz', '120', str(directory / 'fuzz')]),
    ]
    for name, command in commands:
        print(f"\n[{utc()}] EXPECT {name}: all assertions pass, exit 0; command={shlex.join(command)}", flush=True)
        start = time.monotonic()
        entry = dict(name=name, command=command, started_utc=utc())
        report['commands'].append(entry)
        save()
        with (directory / f'{name}.log').open('w') as log:
            child = subprocess.Popen(['timeout', '1200', *command], cwd=ROOT, text=True,
                                     stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                     env=dict(os.environ, VIGIL_EVIDENCE_DIR=str(directory / 'diagnostics'),
                                              ASAN_OPTIONS='detect_leaks=1:halt_on_error=1',
                                              UBSAN_OPTIONS='halt_on_error=1:print_stacktrace=1',
                                              TSAN_OPTIONS='halt_on_error=1'))
            try:
                for line in child.stdout:
                    print(line, end='', flush=True)
                    log.write(line)
                    log.flush()
                entry['exit_code'] = child.wait()
            finally:
                child.stdout.close()
                if child.poll() is None:
                    child.terminate()
                    child.wait(timeout=10)
        entry['elapsed_s'] = time.monotonic() - start
        entry['ended_utc'] = utc()
        save()
        if entry['exit_code'] != 0:
            raise RuntimeError(f"{name} failed, see {directory / (name + '.log')}")
    assert source_digest() == report['source_sha256'], 'implementation changed during gate'
    report['ended_utc'] = utc()
    render(directory, report)
    save()
    print(f"PASS complete checkpoint; generated docs/VERIFICATION.md from {directory}", flush=True)


if __name__ == '__main__':
    main()
